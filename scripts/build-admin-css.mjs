// Builds the CSP-safe admin stylesheets (no CDN, no inline styles):
//   admin/suite.css            ← Tailwind (compiled from the classes used by admin/admin.js + friends)
//   admin/cms/cms-embed.css    ← admin/cms/cms.css scoped under `.cms-embed` so it can live inside the suite
// Usage: node scripts/build-admin-css.mjs   (needs network once for `npx tailwindcss@3.4.19`)
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

execFileSync('npx', ['--yes', 'tailwindcss@3.4.19', '-c', 'scripts/admin-css/tailwind.config.cjs', '-i', 'scripts/admin-css/input.css', '-o', 'admin/suite.css', '--minify'], { stdio: 'inherit' });

const SCOPE = '.cms-embed';
function scopeSelector(sel) {
  sel = sel.trim();
  if (sel === ':root' || sel === 'html' || sel === 'body') return SCOPE;
  if (sel === '*') return `${SCOPE} *`;
  return `${SCOPE} ${sel}`;
}
function scopeBlock(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@media')) out += `${head}{${scopeBlock(body)}}\n`;
    else {
      const sels = [...new Set(head.split(',').map(scopeSelector))].join(',');
      const b = /^(html|body)(,(html|body))*$/.test(head.replace(/\s/g, '')) ? body.replace(/background:var\(--bg\);?/, '') : body;
      out += `${sels}{${b}}\n`;
    }
    i = j;
  }
  return out;
}
const src = readFileSync('admin/cms/cms.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
writeFileSync('admin/cms/cms-embed.css', '/* GENERATED by scripts/build-admin-css.mjs from cms.css — do not edit */\n' + scopeBlock(src));
console.log('admin/suite.css + admin/cms/cms-embed.css written');
